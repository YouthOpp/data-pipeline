import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import {loadSourceManifests} from './source-store.js';

const sourceId = 'at-oead-ernst-mach';
const root = process.argv[2] || 'data-source';
const manifests = await loadSourceManifests(root);
const manifest = manifests.find(item => item.source === sourceId);
assert.ok(manifest?.enabled, 'Reviewed source must remain enabled');
assert.equal(manifest.adapter, 'reviewed-html');
assert.equal(manifest.source_url, manifest.reviewed_page?.url);
const directory = root + '/sources/' + sourceId;
const records = JSON.parse(await readFile(directory + '/opportunities.json', 'utf8'));
const metadata = JSON.parse(await readFile(directory + '/metadata.json', 'utf8'));
const catalog = JSON.parse(await readFile(root + '/catalog.json', 'utf8'));
assert.equal(records.length, 1, 'Exact reviewed notice must yield one genuine record');
const [record] = records;
const expectedId = createHash('sha256').update(sourceId + '|' + manifest.source_url).digest('hex').slice(0, 24);
assert.equal(record.id, expectedId, 'Stable ID mismatch');
assert.equal(record.source, sourceId);
assert.equal(record.source_url, manifest.source_url);
assert.equal(record.url, manifest.reviewed_page.url);
assert.equal(record.title, manifest.reviewed_page.title);
assert.equal(record.category, 'scholarships');
assert.deepEqual(record.categories, ['scholarships']);
assert.equal(record.kind, 'programme-overview');
assert.equal(record.status, 'unknown', 'Do not infer application opening');
assert.equal(record.deadline, null, 'Do not infer the application window');
assert.equal(record.published_at, null, 'No verified original publication timestamp');
assert.equal(record.summary, '', 'Do not copy original publisher prose');
assert.deepEqual(record.eligible_countries, [], 'Do not invent eligibility');
assert.deepEqual(record.host_countries, [], 'Do not infer location from publisher country');
assert.ok(Number.isFinite(Date.parse(record.last_checked_at)), 'Invalid collection timestamp');
assert.equal(record.last_checked_at, metadata.last_checked_at);
assert.equal(record.last_seen_at, metadata.last_checked_at);
assert.equal(metadata.status, 'ok');
assert.equal(metadata.record_count, 1);
assert.equal(metadata.attribution, '© OeAD', 'Missing mandatory attribution');
const matches = catalog.opportunities.filter(item => item.source === sourceId);
assert.equal(matches.length, 1, 'Catalog must contain exactly one source record');
assert.deepEqual(matches[0], record, 'Catalog/snapshot mismatch');
assert.equal(catalog.sources.filter(item => item.source === sourceId).length, 1);
assert.equal(catalog.sources.find(item => item.source === sourceId)?.attribution, '© OeAD');
assert.ok(catalog.indexes.categories.scholarships.includes(record.id));
assert.ok(catalog.indexes.sources[sourceId]?.includes(record.id));
const research = catalog.source_registry.find(item => item.id === 'at-oead');
assert.equal(research?.adapter_source_id, sourceId);
assert.equal(research?.attribution, '© OeAD');
console.log(JSON.stringify({ source: sourceId, qa: 'pass', records: 1, id: record.id, last_checked_at: record.last_checked_at }));
